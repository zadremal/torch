/** The reference scenario. Deterministic: every call returns the same data. */
export function referenceScenario(): RefScenario {
  if (cached) return cached;
  const rnd = random(142);
  const modelCalls: RefModelCall[] = [];
  const toolCalls: RefToolCall[] = [];
  const apiErrors: RefApiError[] = [];
  const spawnToolCallIds = new Map<string, string>();

  for (const spec of AGENTS) {
    const drafts = draftAgent(spec, rnd);
    if (drafts.length !== spec.api) throw new Error(`${spec.id}: ${drafts.length} model calls instead of ${spec.api}`);
    let toolNo = 0;
    let prevCtx = 0;
    drafts.forEach((draft, k) => {
      const turnIndex = k + 1;
      const callId = `req_${spec.id}_${pad(turnIndex, 3)}`;
      let tsStart = ms(draft.start);
      const tsEnd = ms(draft.end);

      const apiError = API_ERRORS.find((e) => e.agent === spec.id && e.turn === turnIndex);
      if (apiError) {
        // A failed attempt is an agent event: the successful attempt is counted from it.
        tsStart += Math.round(Math.min(2000, 0.3 * (tsEnd - tsStart)));
        apiErrors.push({ id: `ref-apierr-${spec.id}`, agentId: spec.id, ts: tsStart, error: apiError.error, statusCode: apiError.statusCode, attempt: 1, maxRetries: 10, retryInMs: 1200 });
      }

      // Context grows from the first call to the peak at the second-to-last; the last one is the mockup's value.
      const ctx = k === spec.api - 1 ? spec.c1 : Math.round(spec.c0 + ((spec.pk - spec.c0) * k) / (spec.api - 2));
      const tokInput = 12 + (k % 5);
      const tokCacheRead = k === 0 ? Math.round(ctx * 0.6) : Math.min(prevCtx, ctx - tokInput);
      const cacheWrite = ctx - tokInput - tokCacheRead;
      prevCtx = ctx;
      const tokOutput = Math.round(180 + rnd() * 1600);
      const tokThinking = spec.model.includes("opus") && rnd() < 0.4 ? Math.round(tokOutput * 0.3) : 0;
      const hourCache = spec.id === MAIN_AGENT_ID;
      const tokens = { tokInput, tokOutput, tokCacheRead, tokCacheWrite5m: hourCache ? 0 : cacheWrite, tokCacheWrite1h: hourCache ? cacheWrite : 0 };

      const tools = draft.tools.map((tool): RefToolCall => {
        const id = `toolu_${spec.id}_${pad(++toolNo, 3)}`;
        if (tool.sub) spawnToolCallIds.set(tool.sub.id, id);
        return {
          id,
          agentId: spec.id,
          modelCallId: callId,
          turnIndex,
          name: tool.name,
          target: tool.name === "Read" || tool.name === "Edit" || tool.name === "Write" ? abs(tool.target) : tool.target,
          input: toolInput(tool),
          output: toolOutput(tool),
          tsStart: ms(tool.start),
          tsEnd: ms(tool.end),
          status: tool.error ? "error" : "ok",
          errorTitle: tool.error?.title ?? null,
          spawnedAgentId: tool.sub?.id ?? null,
          file: toolFile(tool),
          webFetch: tool.name === "WebFetch" ? { url: tool.target, code: 200, bytes: 88268 } : null,
        };
      });
      toolCalls.push(...tools);
      modelCalls.push({
        id: callId,
        agentId: spec.id,
        turnIndex,
        model: spec.model,
        tsStart,
        tsEnd,
        stopReason: tools.length > 0 ? "tool_use" : "end_turn",
        ...tokens,
        tokThinking,
        ctxTokens: ctx,
        costUsd: callCostUsd(spec.model, tokens),
        text: tools.length > 0 ? `Next: ${tools.map((t) => t.name).join(", ")}.` : "Done. Here is a summary of what changed and what is left.",
        thinking: tokThinking > 0 ? "Checking what the previous step returned before choosing the next one." : null,
        toolCallIds: tools.map((t) => t.id),
      });
    });
  }

  const agents = AGENTS.map((spec): RefAgent => ({
    id: spec.id,
    type: spec.type,
    description: spec.description,
    model: spec.model,
    parentAgentId: spec.id === MAIN_AGENT_ID ? null : MAIN_AGENT_ID,
    depth: spec.id === MAIN_AGENT_ID ? 0 : 1,
    spawnToolCallId: spawnToolCallIds.get(spec.id) ?? null,
    sync: spec.sync,
    start: ms(spec.s),
    end: ms(spec.e),
    prompt: spec.prompt,
    instructions: spec.instructions,
  }));

  const prompts: RefPrompt[] = [
    { id: "ref-prompt-1", ts: ms(0), kind: "original", text: USER_PROMPT, attachments: ["Image #1"] },
    ...FOLLOW_UPS.map((f, i): RefPrompt => ({ id: `ref-prompt-${i + 2}`, ts: ms(f.t), kind: "follow_up", text: f.text, attachments: [] })),
  ];

  cached = {
    sessionId: REF_SESSION_ID,
    name: REF_NAME,
    cwd: REF_CWD,
    project: "billing-web",
    startedAt: REF_START,
    endedAt: ms(AGENTS[0]!.e),
    prices: REF_PRICES,
    agents,
    prompts,
    modelCalls,
    toolCalls,
    apiErrors,
  };
  return cached;
}


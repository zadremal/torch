/** Lays out the agent's model and tool calls in time without idle gaps: model response → tools → next response. */
function draftAgent(spec: AgentSpec, rnd: () => number): DraftCall[] {
  const errors = ERRORS.filter((e) => e.agent === spec.id);
  const subs = spec.id === MAIN_AGENT_ID ? AGENTS.filter((a) => a.id !== MAIN_AGENT_ID) : [];
  const anchors: Anchor[] = [
    ...errors.map((e) => ({ t: e.t, d: e.d, name: e.name, target: e.target, error: e, sub: null })),
    ...subs.map((sub) => ({ t: sub.s, d: sub.sync ? sub.e - sub.s : 0.4, name: "Agent", target: sub.description!, error: null, sub })),
  ].sort((a, b) => a.t - b.t);
  const turnEnds = [...(spec.id === MAIN_AGENT_ID ? FOLLOW_UPS.map((f) => f.t) : []), spec.e];

  // Free tools: the mockup's set minus those fixed by anchors.
  const names: string[] = [];
  for (const [name, count] of Object.entries(spec.mix)) {
    if (name === "Agent") continue;
    const forced = errors.filter((e) => e.name === name).length;
    for (let i = 0; i < count - forced; i++) names.push(name);
  }
  for (let i = names.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [names[i], names[j]] = [names[j]!, names[i]!];
  }

  // Segments of free time between the anchors and the ends of turns.
  type Segment = { a: number; b: number; groups: number; anchor: Anchor | null; turnEnd: number | null };
  const points = [...anchors.map((anchor) => ({ t: anchor.t, anchor, turnEnd: null as number | null })), ...turnEnds.map((t) => ({ t, anchor: null as Anchor | null, turnEnd: t }))].sort((x, y) => x.t - y.t);
  const segments: Segment[] = [];
  let cursor = spec.s;
  for (const point of points) {
    const length = point.t - cursor;
    if (point.anchor) {
      segments.push({ a: cursor, b: point.t - Math.min(6, 0.3 * length), groups: 0, anchor: point.anchor, turnEnd: null });
      cursor = point.t + point.anchor.d;
    } else {
      const pause = point.t === spec.e ? 0 : 3;
      segments.push({ a: cursor, b: point.t - pause - Math.min(8, 0.3 * length), groups: 0, anchor: null, turnEnd: point.t - pause });
      cursor = point.t;
    }
  }

  // Groups of free tools (one per model call) are divided among the segments by length.
  const freeGroups = spec.api - anchors.length - turnEnds.length;
  const totalLength = segments.reduce((sum, seg) => sum + (seg.b - seg.a), 0);
  const shares = segments.map((seg) => ((seg.b - seg.a) / totalLength) * freeGroups);
  segments.forEach((seg, i) => (seg.groups = Math.floor(shares[i]!)));
  const byRemainder = segments.map((_, i) => i).sort((x, y) => (shares[y]! % 1) - (shares[x]! % 1));
  for (let left = freeGroups - segments.reduce((sum, seg) => sum + seg.groups, 0), i = 0; left > 0; left--, i++) segments[byRemainder[i]!]!.groups++;

  const groupSizes = Array.from({ length: freeGroups }, () => 1);
  for (let extra = names.length - freeGroups; extra > 0; extra--) groupSizes[Math.floor(rnd() * freeGroups)]!++;

  const calls: DraftCall[] = [];
  let group = 0;
  for (const seg of segments) {
    const window = seg.groups > 0 ? (seg.b - seg.a) / seg.groups : 0;
    for (let j = 0; j < seg.groups; j++) {
      const w0 = seg.a + j * window;
      const w1 = w0 + window;
      const drafts = Array.from({ length: groupSizes[group++]! }, () => {
        const name = names.pop()!;
        const [min, max] = DURATION[name]!;
        const pool = POOL[name]!;
        return { name, target: pool[Math.floor(rnd() * pool.length)]!, duration: Math.min(min + rnd() * (max - min), 0.5 * window) };
      });
      // Tools of one response start together; the longest ends at the window boundary.
      const toolsStart = w1 - Math.max(...drafts.map((d) => d.duration));
      calls.push({ start: w0, end: toolsStart, tools: drafts.map((d) => ({ name: d.name, target: d.target, start: toolsStart, end: toolsStart + d.duration, error: null, sub: null })) });
    }
    const from = seg.groups > 0 ? seg.b : seg.a;
    if (seg.anchor) {
      const { t, d, name, target, error, sub } = seg.anchor;
      calls.push({ start: from, end: t, tools: [{ name, target, start: t, end: t + d, error, sub }] });
    } else {
      calls.push({ start: from, end: seg.turnEnd!, tools: [] });
    }
  }
  return calls;
}

function toolInput(tool: DraftTool): Record<string, unknown> {
  switch (tool.name) {
    case "Bash":
      return { command: tool.target, description: `Run ${tool.target.split(" ").slice(0, 2).join(" ")}`, timeout: 120000 };
    case "Read":
      return { file_path: abs(tool.target) };
    case "Edit":
      return { file_path: abs(tool.target), old_string: 'import { billingFetch } from "./client";', new_string: 'import { client } from "./gen/client.gen";\nimport { InvoiceSchema } from "./schemas";' };
    case "Write":
      return { file_path: abs(tool.target), content: "// generated\n".repeat(124) };
    case "Grep":
      return { pattern: tool.target, path: "src", output_mode: "files_with_matches" };
    case "Glob":
      return { pattern: tool.target };
    case "WebFetch":
      return { url: tool.target, prompt: "How do I enable the Zod plugin?" };
    case "Agent":
      return { subagent_type: tool.sub!.type, description: tool.sub!.description, prompt: tool.sub!.prompt, ...(tool.sub!.sync ? {} : { run_in_background: true }) };
    default:
      return { todos: Array.from({ length: 5 }, (_, i) => ({ content: `Step ${i + 1}`, status: "pending" })) };
  }
}

function toolOutput(tool: DraftTool): string {
  if (tool.error) return tool.error.output;
  switch (tool.name) {
    case "Read":
      return "Read 214 lines (6.8 KB)";
    case "Edit":
      return `Applied 1 edit to ${tool.target} (+6 −3)`;
    case "Write":
      return `Wrote 124 lines to ${tool.target}`;
    case "Bash":
      return `$ ${tool.target}\n${tool.target === "bun test" ? "Ran 44 tests across 9 files.\n 44 pass\n 0 fail" : "exit code 0"}`;
    case "Grep":
      return "Found 12 matches in 7 files";
    case "Glob":
      return "23 files";
    case "WebFetch":
      return "Fetched 86.2 KB, summarised to 1.4K tokens";
    case "Agent":
      return tool.sub!.sync ? `Subagent ${tool.sub!.id} finished and returned its report (2.1K tokens).` : `Async agent launched: ${tool.sub!.id}`;
    default:
      return "Todos updated";
  }
}

function toolFile(tool: DraftTool): RefToolCall["file"] {
  if (tool.name === "Read") return { path: abs(tool.target), op: "read", linesAdded: null, linesRemoved: null };
  // A failed edit does not change the file.
  if (tool.name === "Edit") return { path: abs(tool.target), op: "edit", linesAdded: tool.error ? null : 6, linesRemoved: tool.error ? null : 3 };
  if (tool.name === "Write") return { path: abs(tool.target), op: "write", linesAdded: 124, linesRemoved: 0 };
  return null;
}

function callCostUsd(model: string, call: Pick<RefModelCall, "tokInput" | "tokOutput" | "tokCacheRead" | "tokCacheWrite5m" | "tokCacheWrite1h">): number {
  const price = REF_PRICES.models[model]!;
  const usd =
    (call.tokInput * price.input + call.tokOutput * price.output + call.tokCacheRead * price.cacheRead + call.tokCacheWrite5m * price.cacheWrite5m + call.tokCacheWrite1h * price.cacheWrite1h) / 1_000_000;
  return Math.round(usd * 1e6) / 1e6;
}

